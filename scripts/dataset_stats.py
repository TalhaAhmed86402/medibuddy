#!/usr/bin/env python3
"""Describe a built split (world + scenarios) as Markdown, for docs/DATASET_STATS.md.

  python scripts/dataset_stats.py --data data/dev > docs/DATASET_STATS.md"""
import argparse, collections, json, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from medibuddy_bench.knowledge import LANGUAGE_NAMES

KHIDI = {"en": 92.9, "zh": 65.3, "ru": 59.4, "ja": 40.2, "mn": 35.6, "vi": 17.2, "ar": 12.6}


def load(p):
    with open(p, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def pct(n, d):
    return f"{100 * n / d:.1f}%"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/dev")
    a = ap.parse_args()
    w = json.load(open(os.path.join(a.data, "world.json"), encoding="utf-8"))
    man = json.load(open(os.path.join(a.data, "manifest.json")))
    hs = w["hospitals"]
    sc = {t: load(os.path.join(a.data, f"{t}.jsonl")) for t in man["counts"]}
    print(f"# Dataset statistics ({os.path.basename(a.data.rstrip('/'))} split)\n")
    print(f"Generated by `scripts/dataset_stats.py`. Synthetic data; world hash `{man['world_hash']}`.\n")
    print("## World\n")
    print(f"- {len(hs)} hospitals, {len({h['district'] for h in hs})} districts, "
          f"{len({h['region'] for h in hs})} regions, {len(w['notices'])} live notices.\n")
    tiers = collections.Counter(h["tier"] for h in hs)
    print(table(["Tier", "Hospitals", "Share"], [(t, n, pct(n, len(hs))) for t, n in tiers.most_common()]))
    reg = collections.Counter(h["region"] for h in hs)
    print("\n" + table(["Region", "Hospitals", "Share"], [(r, n, pct(n, len(hs))) for r, n in reg.most_common()]))
    print("\n### Languages supported by hospitals\n")
    lc = collections.Counter(l for h in hs for l in h["languages"])
    rows = []
    for l, n in lc.most_common():
        rows.append((LANGUAGE_NAMES[l], pct(n, len(hs)), KHIDI.get(l, "n/a (assumed)")))
    print(table(["Language", "All synthetic hospitals", "KHIDI list share (real, %)"], rows))
    intl = [h for h in hs if len(h["languages"]) >= 2]
    mean_n = sum(len(h["languages"]) for h in intl) / max(1, len(intl))
    print(f"\n- Hospitals naming 2+ languages: {pct(len(intl), len(hs))}; mean languages among them: {mean_n:.2f}.")
    print(f"- Hospitals with an interpreter service: {pct(sum(h['interpreter_service'] for h in hs), len(hs))}.\n")
    print("## Scenarios\n")
    rows = []
    for t, items in sc.items():
        tc = collections.Counter(s["tier"] for s in items)
        rows.append((t, len(items), tc["L1"], tc["L2"], tc["L3"], tc["L4"]))
    print(table(["Task", "n", "L1", "L2", "L3", "L4"], rows))
    print(f"\nTotal scenarios: {sum(len(v) for v in sc.values())}.\n")
    pers = [s["gold"]["persona"] for t in ("T1", "T2", "T3") for s in sc.get(t, []) if "persona" in s["gold"]]
    if pers:
        nc = collections.Counter(p["nationality"] for p in pers)
        print("### Patient nationalities (T1-T3)\n")
        print(table(["Nationality", "n", "Share"], [(k, n, pct(n, len(pers))) for k, n in nc.most_common()]))
        print(f"\nDistinct names: {len({p['name'] for p in pers})}; distinct visas: {len({p['visa'] for p in pers})}.\n")
    ops = [s["public"].get("opening", "") for t in ("T1", "T2", "T3", "T4") for s in sc.get(t, [])]
    print("### Text variety\n")
    print(f"- Distinct openings (T1-T4): {len(set(ops))} of {len(ops)}.")
    cases = collections.Counter(s["gold"]["case"] for s in sc.get("T4", []))
    print(f"- Triage cases covered (T4): {len(cases)}; labels: "
          + ", ".join(f"{k}={v}" for k, v in collections.Counter(s['gold']['label'] for s in sc.get('T4', [])).items()) + ".")


if __name__ == "__main__":
    main()
